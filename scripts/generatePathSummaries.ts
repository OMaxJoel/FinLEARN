import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { ALL_LEARNING_PATHS_360 } from '../src/data/curriculum360Data';

const summaries = ALL_LEARNING_PATHS_360.map((path) => ({
  id: path.id,
  domainId: path.domainId,
  title: path.title,
  tagline: path.tagline,
  description: path.description,
  estimatedHours: path.estimatedHours,
  competenciesTargeted: path.competenciesTargeted,
  levels: path.levels.map((level) => ({
    id: level.id,
    modules: level.modules.map((module) => ({
      id: module.id,
      title: module.title,
      chapters: module.chapters.map((chapter) => ({
        lessons: chapter.lessons.map(({ id, title }) => ({ id, title })),
      })),
    })),
  })),
}));

await writeFile(resolve(process.cwd(), 'src/data/pathDashboardSummaries.ts'),
  `// Generated by scripts/generatePathSummaries.ts. Keep learner-facing content out of the home bundle.\n` +
  `export interface DashboardPathSummary { id: string; domainId: string; title: string; tagline: string; description: string; estimatedHours: number; competenciesTargeted: string[]; levels: { id: string; modules: { id: string; title: string; chapters: { lessons: { id: string; title: string }[] }[] }[] }[] }\n` +
  `export const PATH_DASHBOARD_SUMMARIES: DashboardPathSummary[] = ${JSON.stringify(summaries, null, 2)};\n`
);
